# ---------------------------------------------------------------------------
# image_audio_to_video (requires ffmpeg)
# ---------------------------------------------------------------------------

@pytest.mark.skipif(not check_ffmpeg(), reason="ffmpeg not installed")
class TestImageAudioToVideo:
    def test_creates_mp4_file(self, tmp_path: Path):
        image = make_tiny_jpeg(tmp_path / "bg.jpg")
        audio = make_short_mp3(tmp_path / "audio.mp3", duration_ms=2_000)
        out = tmp_path / "output.mp4"

        result = image_audio_to_video(image, audio, out)

        assert result == out
        assert out.exists()
        assert out.stat().st_size > 0

    def test_missing_image_raises(self, tmp_path: Path):
        audio = make_short_mp3(tmp_path / "audio.mp3")
        with pytest.raises(FileNotFoundError, match="Background image not found"):
            image_audio_to_video(tmp_path / "missing.jpg", audio, tmp_path / "out.mp4")

    def test_missing_audio_raises(self, tmp_path: Path):
        image = make_tiny_jpeg(tmp_path / "bg.jpg")
        with pytest.raises(FileNotFoundError, match="Audio file not found"):
            image_audio_to_video(image, tmp_path / "missing.mp3", tmp_path / "out.mp4")

    def test_output_in_specified_directory(self, tmp_path: Path):
        image = make_tiny_jpeg(tmp_path / "bg.jpg")
        audio = make_short_mp3(tmp_path / "audio.mp3")
        out_dir = tmp_path / "results"
        out = out_dir / "video.mp4"

        image_audio_to_video(image, audio, out)

        assert out.exists()
        assert out.parent == out_dir
