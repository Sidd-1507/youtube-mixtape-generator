def make_short_mp3(path: Path, duration_ms: int = 2_000) -> Path:
    """Create a short synthetic MP3 file for testing."""
    seg = Sine(440).to_audio_segment(duration=duration_ms)
    seg.export(str(path), format="mp3")
    return path


